/*
 * hub.h - ハブ (送信の装置のデータを集めて、スマホのブラウザに表示する)
 *
 * ネットワークは、次のどちらかです。
 *   - Wi-Fi (ルーター) に接続する: 設定ページで SSID を設定したとき。ルーターのチャンネルで
 *     動きます。スマホは、同じネットワークから http://<IP アドレス>/ または
 *     http://pressure-hub.local/ を開きます。IP アドレスはシリアルに出し、設定ページにも表示します。
 *     HUB_KEEP_AP_WITH_STA なら、自分のアクセスポイントも立ち上げたままにします。スマホを
 *     それにつなげば、PC がなくても、割り当てられた IP アドレスを、表示ページの上部で確認できます
 *     (/info が、ネットワークの状況を JSON で返す)。
 *     HUB_STA_TIMEOUT_MS 以内につながらなければ、自分でアクセスポイントになります。
 *     一度つながった後に切れたときは、再接続を続けます。
 *   - 自分でアクセスポイントになる: SSID が空のとき。HUB_SSID (パスワードなし) を、
 *     設定ページのチャンネル (hubChannel) で立ち上げます。スマホは、これに接続して http://192.168.4.1/ を開きます。
 * どちらの場合も、同じチャンネルの ESP-NOW を受信し、送信の装置がチャンネルを見つけられるよう、
 * ビーコンを送ります (link.h)。ESP-NOW を取りこぼさないよう、Wi-Fi の省電力は切っています。
 *
 * 設定モードと違い、キャプティブポータル (接続したときに自動で開くページ) にはしません。
 * 自動で開く簡易ブラウザでは、画面を点けたままにする機能や、CSV の保存が使えないため、
 * Safari や Chrome で開いてもらいます。
 *
 * 受信したパケットは、HUB_PUSH_INTERVAL_MS ごとに、1 つのバイナリのフレームにまとめて、
 * WebSocket (/ws) で、全てのスマホへ送ります。
 * フレームの形式 (リトルエンディアン)
 *   0  'H'
 *   1  version  (1)
 *   2  count    レコード数 (uint16)
 *   4  hubMs    送った時刻 (ハブの millis)
 *   8  dropped  ハブが取りこぼしたパケット数の累計 (受信のキューがいっぱい、など)
 *  12  レコード x count
 *        0  rxMs   受信した時刻 (ハブの millis)
 *        4  rssi   電波の強さ [dBm] (int8)。ハブ自身のデータは 0
 *        5  len    パケットの長さ
 *        6  mac[6] 送信元の MAC アドレス
 *       12  パケット (link.h) x len バイト
 */
#pragma once

#include <stdint.h>
#include <stddef.h>

bool hubBegin();                          // アクセスポイント、ESP-NOW、Web サーバを起動する
void hubService(uint32_t nowMs);          // ループから毎回呼ぶ
void hubAcceptLocal(const uint8_t *pkt, size_t len);   // ハブ自身のパケット
