/*
 * sound.h - 音 (Modulino Buzzer)
 *
 * Qwiic コネクタに Arduino Modulino Buzzer (ABX00108) をつなぐと、LED1 の色 (気圧の変化) に合わせて、
 * コード進行のアルペジオを鳴らします。つないでいなければ、何もしません (起動時に I2C で探す)。
 *
 * Modulino Buzzer は、基板上のマイコン (STM32C011) が、圧電ブザー (PKLCS1212E4001、約 4kHz で
 * 最も大きく鳴る) を鳴らします。I2C (7 ビットのアドレス 0x1E) で、周波数 [Hz] と長さ [ms] を
 * 4 バイトずつ (リトルエンディアン) 送ると、その音を鳴らします。音の長さは、Modulino の側が
 * 数えるので、鳴っている間も、こちらはライトスリープに入れます。
 * (Arduino_Modulino ライブラリの ModulinoBuzzer::tone() と同じ形式。ライブラリは使わない)
 *
 * 鳴らし方
 *   - LED1 が点灯している (変化量が不感帯の外にある) 間は、1 小節ずつコードを進めながら、
 *     アルペジオを鳴らし続ける。不感帯に入ると、鳴っている音もすぐに止めて、無音にする
 *   - 気圧が上がる (+) ときは明るい C メジャー (C - G - Am - Em - F - C - Dm - G)、
 *     下がる (-) ときは暗い C マイナー (Cm - Ab - Eb - Bb - Fm - Cm - Dm(-5) - G) の進行
 *   - 豪華さ (5 段階): 変化が大きいほど、また長く続くほど、使うコードの音 (三和音 → 7 度 →
 *     9 度)、1 小節の音の数 (3 → 12)、速さ、音域を増やす。いちばん豪華な段階では、
 *     小節の最後に高い音を飾る
 *   - 長く続くほど (2 秒、6 秒、15 秒で段階が上がる)、基準の高さも少しずつ上げて、盛り上げる
 *   - 同じ音ばかりにならないように: 短い無音のあとは、コード進行の続きから鳴らす。
 *     鳴り始めるたびに、基準の高さを少しずらし、音の並びの形も変える (小節ごとにも変える)
 *   - 基準の音の高さは、変化量の絶対値に比例させる (SOUND_BASE_LOW〜HIGH)。小節の始まりに、
 *     基準に最も近いコードの音から並べるので、高さが変わっても、つながりが自然になる
 *   - 瞬間的な変化 (変化量が短い時間に大きく増えた) では、今の小節を打ち切り、コードの音で
 *     速く駆け上がる (変化が大きいほど、音が多く、高い)
 * 音色 (settings の sound)
 *   キラキラ : 速いアルペジオ (段階により約 33〜133ms ごと)
 *   さわやか : ゆったりした分散和音 (段階により約 66〜200ms ごと)
 */
#pragma once

#include <stdint.h>

// 起動時に呼ぶ。I2C (Wire) を初期化したあと (sensorBegin のあと) に呼ぶこと
void soundBegin();

// Modulino Buzzer が見つかったか
bool soundAvailable();

// 毎ティック呼ぶ。level は、変化量を表示の範囲で表した値 (palette.h の deltaLevel。-1000〜1000。
// 不感帯の中は 0)。鳴らすかを決めて、鳴らしている途中のフレーズの、次の音を送る
void soundTick(uint32_t nowMs, int32_t level);

// 設定ページで音色を変えたときに、試しに鳴らす (Web サーバのタスクから呼べる。
// 実際に鳴らすのは、次の soundTick)
void soundRequestPreview();
